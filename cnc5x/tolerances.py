"""全库的数值容差，集中在这里管理。

容差只有两种用途：吸收浮点舍入，或者判断退化情形（极点、方向相反、近乎直线）。
它们不进入公式，分母上不加 epsilon。改动任何一个值之前，先读它旁边的理由。
"""

# ---------- 浮点舍入 ----------

# 相对舍入容差：参数略微越出定义域、长度略微不够、时长略微超过整数个周期时，
# 若偏差在这个比例以内，就当作舍入误差处理。双精度下经过几十步累加，
# 误差约��� 1e-13–1e-12，这里放宽到 1e-9，但仍远小于任何有物理意义的量。
ROUNDING = 1e-9

# brentq 求峰值速度的绝对精度（mm/s 或 rad/s）。比进给速度的有效位数小得多。
ROOT_XTOL = 1e-12

# ---------- 弧长表 ----------

# 弧长表每一小段允许的绝对误差（与弧长同单位：mm；按刀轴计量时为 rad）。
# 1e-7 mm = 0.1 nm，比插补点的弓高误差（通常 1e-3 mm）小四个数量级，
# 所以弧长表的误差不会在进给速度波动里显现。
ARC_LENGTH = 1e-7

# 自适应细分的最大层数。每层把一���对半分，40 层即段长缩小到 2⁻⁴⁰ ≈ 1e-12 倍，
# 超过这个层数还不收敛，说明曲线本身有问题（例如接近零速度的点）。
ARC_LENGTH_MAX_DEPTH = 40

# ---------- 退化情形 ----------

# 刀轴与 C 轴平行（极点）的判据：C 角对应的复数 w = sin(倾角)·e^{iC}，
# |w| < 1e-9 即倾角小于 1e-9 rad。此时 C 角由舍入噪声决定，没有意义。
POLE = 1e-9

# 两方向夹角与 π 之差小于它（rad）时视为方向相反，大圆弧不唯一。
# 夹角离 π 为 δ 时，求切向要除以约 δ 的量，1e-9 时仍有约 7 位有效数字。
ANTIPODAL = 1e-9

# 曲率低于全曲线最大曲率的这个比例时视为直线段，其上的"峰值"只是舍入噪声。
FLAT_CURVATURE = 1e-6
