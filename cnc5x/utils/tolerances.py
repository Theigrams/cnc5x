"""全库的数值容差，集中在这里管理。

容差只有两种用途：吸收浮点舍入，或者判断退化情形（极点、方向相反、近乎直线）。
它们不进入公式，分母上不加 epsilon。改动任何一个值之前，先读它旁边的理由。
"""

# ---------- 浮点舍入 ----------

# 相对舍入容差。参数略微越出定义域、路程略微不够、时长略微超过整数个周期时，
# 偏差在这个比例以内就当作舍入误差。双精度经过几十步累加，相对误差约为 1e-13 到 1e-12，
# 这里放宽到 1e-9，仍然远小于任何有物理意义的量。
ROUNDING = 1e-9

# brentq 求峰值速度时的绝对精度（mm/s 或 rad/s），远小于进给速度的有效位数。
ROOT_XTOL = 1e-12

# ---------- 弧长表 ----------

# 弧长表每一小段允许的误差，单位与弧长相同（mm；按刀轴计量时为 rad）。
# 1e-8 mm = 0.01 nm，比任何有物理意义的长度都小 5 个数量级以上，弧长表误差不会出现在任何指标里。
# 三次 Hermite 的误差与段长的四次方成正比，容差每缩小 10 倍，段数增加约 1.8 倍。拐角光顺的刀路
# 要为上千条短过渡曲线各建一张表（griffen 数据上约 2200 张），所以不取更严的 1e-9。
ARC_LENGTH = 1e-8

# 自适应细分最多对分的次数。对分 40 次后段长缩小到原来的 2⁻⁴⁰ ≈ 1e-12；
# 到这时还不收敛，说明曲线有速度接近零的点，不能用弧长作参数。
ARC_LENGTH_MAX_DEPTH = 40

# ---------- 退化情形 ----------

# 刀轴平行于 C 轴（极点）的判据。C 角对应的复数 w 满足 |w| = sin(倾角)，
# |w| < 1e-9 即倾角小于 1e-9 rad，这时 C 角完全由舍入噪声决定。
POLE = 1e-9

# 两方向的夹角离 π 小于这个值（rad）时视为方向相反，大圆弧不唯一。
# 离 π 为 δ 时，切向由长度约为 δ 的向量单位化得到，舍入误差放大约 1/δ 倍；
# δ = 1e-6 时仍有约 10 位有效数字。
ANTIPODAL = 1e-6

# 曲率低于全曲线最大曲率的这个比例时视为直线，这里出现的"峰值"只是舍入噪声。
FLAT_CURVATURE = 1e-6
